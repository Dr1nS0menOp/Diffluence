// Package storage keeps files outside the database. Disk is the store for
// single-node installs; an S3 store implements the same interface in phase 3.
package storage

import (
	"context"
	"crypto/sha256"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"time"

	"github.com/jackc/pgx/v5"
)

// ErrNotFound means the object does not exist.
var ErrNotFound = errors.New("storage: object not found")

// ErrTooLarge means the input exceeded the limit given to Put.
var ErrTooLarge = errors.New("storage: object too large")

// QueueDeletion schedules a stored file for removal, inside the caller's
// transaction, so a crash can never leave a file behind for good.
func QueueDeletion(ctx context.Context, tx pgx.Tx, key string) error {
	if _, err := tx.Exec(ctx, "INSERT INTO storage_deletions (object_key) VALUES ($1) ON CONFLICT DO NOTHING", key); err != nil {
		return fmt.Errorf("storage: queue deletion: %v", err)
	}
	return nil
}

// Object is the result of storing a file.
type Object struct {
	Size   int64
	SHA256 []byte
}

// Store keeps objects by key.
type Store interface {
	// Put stores r under key. Nothing remains when it fails.
	Put(ctx context.Context, key string, r io.Reader, maxBytes int64) (Object, error)
	Open(ctx context.Context, key string) (io.ReadSeekCloser, error)
	Delete(ctx context.Context, key string) error
	// List names every stored object, for finding what nothing points at.
	List(ctx context.Context) ([]Listed, error)
	Healthy(ctx context.Context) error
}

// Listed is one stored object.
type Listed struct {
	Key      string
	Size     int64
	Modified time.Time
}

var keyPattern = regexp.MustCompile(`^[a-z0-9-]+(/[a-z0-9-]+)*$`)

// Disk stores objects as files below a root directory.
type Disk struct {
	root string
}

// NewDisk creates the root directory if needed.
func NewDisk(root string) (*Disk, error) {
	if err := os.MkdirAll(root, 0o700); err != nil {
		return nil, fmt.Errorf("storage: %w", err)
	}
	return &Disk{root: root}, nil
}

func (d *Disk) path(key string) (string, error) {
	// Keys are generated by us, but a store must not depend on that.
	if !keyPattern.MatchString(key) || strings.Contains(key, "..") {
		return "", fmt.Errorf("storage: invalid key %q", key)
	}
	return filepath.Join(d.root, filepath.FromSlash(key)), nil
}

// Put writes to a temporary file first, so readers never see half a file.
func (d *Disk) Put(ctx context.Context, key string, r io.Reader, maxBytes int64) (Object, error) {
	path, err := d.path(key)
	if err != nil {
		return Object{}, err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return Object{}, err
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), ".upload-*")
	if err != nil {
		return Object{}, err
	}
	defer func() { _ = os.Remove(tmp.Name()) }()
	defer func() { _ = tmp.Close() }()

	h := sha256.New()
	n, err := io.Copy(io.MultiWriter(tmp, h), io.LimitReader(contextReader{ctx, r}, maxBytes+1))
	if err != nil {
		return Object{}, err
	}
	if n > maxBytes {
		return Object{}, ErrTooLarge
	}
	if err := tmp.Sync(); err != nil {
		return Object{}, err
	}
	if err := tmp.Close(); err != nil {
		return Object{}, err
	}
	if err := os.Rename(tmp.Name(), path); err != nil {
		return Object{}, err
	}
	return Object{Size: n, SHA256: h.Sum(nil)}, nil
}

type contextReader struct {
	ctx context.Context
	r   io.Reader
}

func (c contextReader) Read(p []byte) (int, error) {
	if err := c.ctx.Err(); err != nil {
		return 0, err
	}
	return c.r.Read(p)
}

// Open opens an object for reading.
func (d *Disk) Open(_ context.Context, key string) (io.ReadSeekCloser, error) {
	path, err := d.path(key)
	if err != nil {
		return nil, err
	}
	f, err := os.Open(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil, ErrNotFound
	}
	return f, err
}

// Delete removes an object. Deleting a missing object is not an error, so the
// cleanup job can safely run twice.
func (d *Disk) Delete(_ context.Context, key string) error {
	path, err := d.path(key)
	if err != nil {
		return err
	}
	if err := os.Remove(path); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	return nil
}

// List walks the root. Temporary files of uploads under way are left out.
func (d *Disk) List(ctx context.Context) ([]Listed, error) {
	out := []Listed{}
	err := filepath.WalkDir(d.root, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if ctx.Err() != nil {
			return ctx.Err()
		}
		if entry.IsDir() || strings.HasPrefix(entry.Name(), ".") {
			return nil
		}
		info, err := entry.Info()
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(d.root, path)
		if err != nil {
			return err
		}
		out = append(out, Listed{Key: filepath.ToSlash(rel), Size: info.Size(), Modified: info.ModTime()})
		return nil
	})
	return out, err
}

// Healthy checks that the store accepts writes.
func (d *Disk) Healthy(_ context.Context) error {
	tmp, err := os.CreateTemp(d.root, ".health-*")
	if err != nil {
		return err
	}
	_ = tmp.Close()
	return os.Remove(tmp.Name())
}
